export function getFallbackBlogPosts(region?: string): BlogPost[] {
  if (!region || region === 'int' || region === 'global') {
    return fallbackBlogPosts;
  }
  const filtered = fallbackBlogPosts.filter((p) => p.region === region || p.region === 'global');
  return filtered.length ? filtered : fallbackBlogPosts;
}

export function getFallbackBlogPost(slug: string): BlogPost | null {
  return fallbackBlogPosts.find((p) => p.slug === slug || p.id === slug) || null;
}

export function getFallbackRelatedPosts(category: string, currentId: string): BlogPost[] {
  return fallbackBlogPosts.filter((p) => p.id !== currentId).slice(0, 3);
}

